<?php
/**
 * The runtime a visitor's request runs to put a half-made swap back.
 *
 * @package WPCheckpoint
 */

namespace WPCheckpoint\Jobs;

use WPCheckpoint\Restore\Maintenance;
use WPCheckpoint\Support\AtomicFile;
use WPCheckpoint\Support\HostFunctions;

defined( 'ABSPATH' ) || exit;

/**
 * Written by the swap (in WordPress, its plugin directory in place) next to the maintenance file before it first puts it
 * up (Restore\Maintenance::RUNTIME): every class a run without WordPress needs (WebClasses::ALL), from this plugin's
 * own files, in one file, so that a request the maintenance file holds can run it while the plugin's directory is one
 * the swap renamed. Its first lines name the restore (Restore\Maintenance::WEB_MARK) and return false unless the
 * maintenance file's code defined WPCHECKPOINT_WEB_ENTRY (requested directly, it does nothing and says nothing); then
 * returns false as well, with a line in the runtime log (LOADED), when one of its classes is there already (a request
 * that had loaded this plugin: declaring the class again would be a fatal error); then
 * each class file as a bracketed namespace, its declaration inside a condition (PHP declares a file's unconditional
 * classes as it compiles the file, before that look), a parent, an interface or a trait before what uses it; it returns its
 * hash, the SHA-256 of those class files as written into it (the body), which the data file names too: the
 * maintenance file's code gives both to WebEntry::run(), which does nothing when they differ (a host's OPcache may run
 * an older file's code under the same name). No class file may use __DIR__, __FILE__ or __LINE__ outside a string
 * (their values would be the runtime's, not the file's): one that does stops the swap before anything changed.
 */
final class WebRuntime {

	/**
	 * The constant only the maintenance file's code defines (Restore\Maintenance::CODE).
	 */
	const ENTRY = 'WPCHECKPOINT_WEB_ENTRY';

	/**
	 * What the runtime writes into its log when it finds one of its classes there already (guard()).
	 */
	const LOADED = 'A request that had loaded this plugin before the site was held read the maintenance file: it puts nothing back.';

	/**
	 * The runtime for a restore, and its hash.
	 *
	 * @param string        $mark    The restore's mark (Restore\Maintenance::new_mark()).
	 * @param string[]|null $classes Classes, WebClasses::ALL when null (tests give others).
	 * @param string|null   $src     The plugin's src/ directory (this one when null).
	 * @return array{code: string, hash: string}
	 * @throws \RuntimeException When a class file cannot be read or uses __DIR__, __FILE__ or __LINE__ outside a string.
	 */
	public static function build( string $mark, $classes = null, $src = null ): array {
		$src   = null === $src ? dirname( __DIR__ ) : rtrim( (string) $src, '/\\' );
		$body  = '';
		$order = self::order( null === $classes ? WebClasses::ALL : $classes );
		foreach ( $order as $class ) {
			$body .= self::block( $class, $src . '/' . str_replace( '\\', '/', substr( $class, strlen( 'WPCheckpoint\\' ) ) ) . '.php' );
		}
		$hash = hash( 'sha256', $body );
		$code = "<?php\n# " . $mark . "\n"
			. "// WP Checkpoint: the code a request held by the maintenance file runs to put a half-made restore back. Generated by the restore; taken down with the maintenance file.\n"
			. "namespace {\nif ( ! defined( '" . self::ENTRY . "' ) ) {\n\treturn false;\n}\n"
			. self::guard( $order )
			. "}\n"
			. $body
			. "namespace {\nreturn '" . $hash . "';\n}\n";
		return array(
			'code' => $code,
			'hash' => $hash,
		);
	}

	/**
	 * Write the runtime for a restore next to its maintenance file (whole or not at all, AtomicFile; OPcache told).
	 *
	 * @param string        $dir     The WordPress directory.
	 * @param string        $mark    The restore's mark.
	 * @param callable|null $confirm Called right before it goes in place (the lease; throws to stop).
	 * @return string Its hash.
	 * @throws \RuntimeException When it cannot be made or written.
	 */
	public static function write( string $dir, string $mark, $confirm = null ): string {
		$built   = self::build( $mark );
		$options = array(
			'check' => static function ( string $temporary ): void {
				if ( false === HostFunctions::lint( $temporary ) ) {
					throw new \WPCheckpoint\Support\AtomicWriteFailed( 'The runtime does not pass php -l.' );
				}
			},
		);
		if ( null !== $confirm ) {
			$options['confirm'] = $confirm;
		}
		AtomicFile::write( $dir, Maintenance::RUNTIME, $built['code'], $options );
		HostFunctions::opcache_invalidate( rtrim( $dir, '/\\' ) . DIRECTORY_SEPARATOR . Maintenance::RUNTIME );
		return $built['hash'];
	}

	/**
	 * Classes in the order they can be declared in: each after its parent, its interfaces and its traits (of the list).
	 *
	 * @param string[] $classes Classes.
	 * @return string[]
	 * @throws \RuntimeException When a class cannot be found.
	 */
	public static function order( array $classes ): array {
		$out    = array();
		$seen   = array();
		$need   = array_fill_keys( $classes, true );
		$add    = static function ( string $name ) use ( &$add, &$out, &$seen, $need ): void {
			if ( isset( $seen[ $name ] ) ) {
				return;
			}
			$seen[ $name ] = true;
			if ( ! class_exists( $name ) && ! interface_exists( $name ) && ! trait_exists( $name ) ) {
				throw new \RuntimeException( sprintf( 'The runtime needs %s, which this plugin does not have.', $name ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped -- a class name.
			}
			$reflection = new \ReflectionClass( $name );
			$before     = $reflection->getInterfaceNames();
			$parent     = $reflection->getParentClass();
			if ( false !== $parent ) {
				$before[] = $parent->getName();
			}
			foreach ( array_merge( $before, $reflection->getTraitNames() ) as $first ) {
				if ( isset( $need[ $first ] ) ) {
					$add( $first );
				}
			}
			$out[] = $name;
		};
		$sorted = $classes;
		sort( $sorted );
		foreach ( $sorted as $class ) {
			$add( $class );
		}
		return $out;
	}

	/**
	 * A class file as a bracketed namespace.
	 *
	 * @param string $name Class.
	 * @param string $path Its file.
	 * @return string
	 * @throws \RuntimeException When it cannot be read, is not of the form, or uses __DIR__, __FILE__ or __LINE__.
	 */
	private static function block( string $name, string $path ): string {
		$source = @file_get_contents( $path ); // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged,WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- a class file of this plugin; the exception says it.
		if ( ! is_string( $source ) || 1 !== preg_match( '/\A<\?php\r?\n/', $source, $open ) ) {
			throw new \RuntimeException( sprintf( 'The runtime cannot read the file of %s.', $name ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped -- a class name.
		}
		$used = self::magic( $source );
		if ( '' !== $used ) {
			throw new \RuntimeException( sprintf( 'The file of %1$s uses %2$s outside a string, which would say the runtime\'s value, not its own; the swap was not started.', $name, $used ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped -- a class name and a constant's.
		}
		$count = 0;
		$body  = preg_replace( '/^namespace\s+([A-Za-z0-9_\\\\]+)\s*;/m', 'namespace $1 {', substr( $source, strlen( $open[0] ) ), 1, $count ); // Windows line endings too (a checkout, an upload in text mode).
		if ( ! is_string( $body ) || 1 !== $count ) {
			throw new \RuntimeException( sprintf( 'The file of %s is not of the form the runtime takes (one namespace statement).', $name ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped -- a class name.
		}
		// The declaration inside a condition: PHP declares a file's unconditional classes as it compiles the file,
		// before guard() could look, and each would seem to be there already.
		$body  = rtrim( $body );
		$found = preg_match_all( '/^(?:(?:final|abstract)[ \t]+)?(?:class|interface|trait)[ \t]+[A-Za-z_][A-Za-z0-9_]*\b/m', $body, $at, PREG_OFFSET_CAPTURE );
		if ( 1 !== $found || '}' !== substr( $body, -1 ) ) {
			throw new \RuntimeException( sprintf( 'The file of %s is not of the form the runtime takes (one class, its declaration at the start of a line, the file ending with it).', $name ) ); // phpcs:ignore WordPress.Security.EscapeOutput.ExceptionNotEscaped -- a class name.
		}
		$start = (int) $at[0][0][1];
		return substr( $body, 0, $start ) . "if ( true ) {\n" . substr( $body, $start ) . "\n}\n}\n";
	}

	/**
	 * The runtime's check of the process it is included in, after its first lines: when any of its classes is there
	 * already (a request that had loaded this plugin before the site was held, reading the maintenance file as it
	 * ends), declaring them would be a fatal error; it writes one line into the runtime log and returns false, and
	 * that request puts nothing back.
	 *
	 * @param string[] $classes The classes it declares.
	 * @return string PHP statements.
	 */
	private static function guard( array $classes ): string {
		$names = '';
		foreach ( $classes as $class ) {
			$names .= "\t'" . str_replace( '\\', '\\\\', $class ) . "',\n";
		}
		return 'foreach ( array(' . "\n" . $names . ') as $wpcheckpoint_class ) {' . "\n"
			. "\t" . 'if ( class_exists( $wpcheckpoint_class, false ) || interface_exists( $wpcheckpoint_class, false ) || trait_exists( $wpcheckpoint_class, false ) ) {' . "\n"
			. "\t\t" . '$wpcheckpoint_log = @fopen( __DIR__ . \'/' . Maintenance::LOG . '\', \'r+\' );' . "\n"
			. "\t\t" . 'if ( false !== $wpcheckpoint_log ) {' . "\n"
			. "\t\t\t" . '@fseek( $wpcheckpoint_log, 0, SEEK_END );' . "\n"
			. "\t\t\t" . '@fwrite( $wpcheckpoint_log, gmdate( \'Y-m-d H:i:s\' ) . " ' . self::LOADED . '\\n" );' . "\n"
			. "\t\t\t" . '@fclose( $wpcheckpoint_log );' . "\n"
			. "\t\t" . '}' . "\n"
			. "\t\t" . 'unset( $wpcheckpoint_class, $wpcheckpoint_log );' . "\n"
			. "\t\t" . 'return false;' . "\n"
			. "\t" . '}' . "\n"
			. '}' . "\n"
			. 'unset( $wpcheckpoint_class );' . "\n";
	}

	/**
	 * Which of __DIR__, __FILE__ and __LINE__ a source uses outside a string ('' for none): by its tokens, read only
	 * when the name is in it at all.
	 *
	 * @param string $source PHP source.
	 * @return string
	 */
	public static function magic( string $source ): string {
		if ( false === strpos( $source, '__DIR__' ) && false === strpos( $source, '__FILE__' ) && false === strpos( $source, '__LINE__' ) ) {
			return '';
		}
		foreach ( token_get_all( $source ) as $token ) {
			if ( is_array( $token ) && in_array( $token[0], array( T_DIR, T_FILE, T_LINE ), true ) ) {
				return $token[1];
			}
		}
		return '';
	}
}
